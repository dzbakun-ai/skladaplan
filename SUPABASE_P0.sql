-- 1) Reconcile a previously-created legacy movement table.
-- If it contains data, stop rather than silently converting history.
do $$
declare
  bad boolean := false;
  rows_count bigint;
begin
  if to_regclass('public.box_movements') is not null then
    select count(*) into rows_count from public.box_movements;
    select exists (
      select 1
      from information_schema.columns
      where table_schema='public'
        and table_name='box_movements'
        and column_name in ('box_id','from_warehouse_id','to_warehouse_id','from_location_id','to_location_id','from_pallet_id','to_pallet_id')
        and data_type <> 'bigint'
    ) into bad;
    if bad and rows_count > 0 then
      raise exception 'P0 STOP: box_movements contains legacy non-bigint IDs and existing history. Export/reconcile it before migration.';
    elsif bad then
      drop table public.box_movements cascade;
    end if;
  end if;
end $$;

-- 1) Ensure movement table exists with the same bigint FK domain as boxes.
create table if not exists public.box_movements (
  id bigint generated by default as identity primary key,
  box_id bigint references public.boxes(id) on delete set null,
  barcode text,
  from_warehouse_id bigint references public.warehouses(id),
  to_warehouse_id bigint references public.warehouses(id),
  from_location_id bigint references public.locations(id),
  to_location_id bigint references public.locations(id),
  from_pallet_id bigint references public.pallets(id),
  to_pallet_id bigint references public.pallets(id),
  from_warehouse_text text,
  to_warehouse_text text,
  from_zone_text text,
  to_zone_text text,
  from_pallet_text text,
  to_pallet_text text,
  reason text not null default 'move',
  operator text,
  moved_at timestamptz not null default now()
);

alter table public.box_movements enable row level security;

