create or replace function public.sp_move_boxes(
  p_box_ids bigint[], p_target_warehouse text, p_target_zone text,
  p_target_pallet text, p_operator text, p_reason text default 'move'
)
returns setof public.boxes
language plpgsql security definer set search_path = public
as $$
declare
  v_warehouse_id public.warehouses.id%type;
  v_location_id public.locations.id%type;
  v_pallet_id public.pallets.id%type;
  v_count integer;
begin
  if not public.skladaplan_is_admin() then
    raise exception 'FORBIDDEN: admin role required';
  end if;
  if coalesce(array_length(p_box_ids,1),0) = 0 then
    raise exception 'EMPTY_BOX_LIST';
  end if;

  if nullif(trim(p_target_warehouse),'') is not null then
    select id into v_warehouse_id from public.warehouses where name=trim(p_target_warehouse) limit 1;
    if v_warehouse_id is null then raise exception 'WAREHOUSE_NOT_FOUND: %', p_target_warehouse; end if;
  end if;

  if nullif(trim(p_target_zone),'') is not null then
    select id into v_location_id from public.locations
    where code=trim(p_target_zone)
      and (v_warehouse_id is null or warehouse_id=v_warehouse_id) limit 1;
    if v_location_id is null then raise exception 'LOCATION_NOT_FOUND: %', p_target_zone; end if;
  end if;

  if nullif(trim(p_target_pallet),'') is not null then
    select id into v_pallet_id from public.pallets
    where pallet_number=trim(p_target_pallet)
      and (v_warehouse_id is null or warehouse_id=v_warehouse_id) limit 1;
    if v_pallet_id is null then raise exception 'PALLET_NOT_FOUND: %', p_target_pallet; end if;
  end if;

  insert into public.box_movements (
    box_id, barcode, from_warehouse_id, to_warehouse_id,
    from_location_id, to_location_id, from_pallet_id, to_pallet_id,
    from_warehouse_text, to_warehouse_text, from_zone_text, to_zone_text,
    from_pallet_text, to_pallet_text, reason, operator
  )
  select b.id,b."Штрихкод",b.warehouse_id,v_warehouse_id,
         b.location_id,v_location_id,b.pallet_id,v_pallet_id,
         b."Склад",p_target_warehouse,b."Зона/ряд",p_target_zone,
         b."Поддон",p_target_pallet,coalesce(nullif(p_reason,''),'move'),p_operator
  from public.boxes b where b.id=any(p_box_ids);

  update public.boxes
  set "Склад"=coalesce(nullif(trim(p_target_warehouse),''),"Склад"),
      "Зона/ряд"=coalesce(nullif(trim(p_target_zone),''),"Зона/ряд"),
      "Поддон"=coalesce(nullif(trim(p_target_pallet),''),"Поддон"),
      warehouse_id=coalesce(v_warehouse_id,warehouse_id),
      location_id=coalesce(v_location_id,location_id),
      pallet_id=coalesce(v_pallet_id,pallet_id),
      "Изменил"=p_operator
  where id=any(p_box_ids) returning *;
end;
$$;

drop function if exists public.sp_merge_pallets(jsonb, text, text, text, text);
create or replace function public.sp_merge_pallets(
  p_source_pallets jsonb, p_target_warehouse text, p_target_zone text,
  p_target_pallet text, p_operator text
)
returns integer
language plpgsql security definer set search_path = public
as $$
declare
  v_warehouse_id public.warehouses.id%type;
  v_location_id public.locations.id%type;
  v_pallet_id public.pallets.id%type;
  v_moved_count integer;
begin
  if not public.skladaplan_is_admin() then raise exception 'FORBIDDEN: admin role required'; end if;
  if jsonb_typeof(p_source_pallets) <> 'array' or jsonb_array_length(p_source_pallets)=0 then raise exception 'EMPTY_SOURCE_PALLETS'; end if;

  select id into v_warehouse_id from public.warehouses where name=trim(p_target_warehouse) limit 1;
  if v_warehouse_id is null then raise exception 'WAREHOUSE_NOT_FOUND: %', p_target_warehouse; end if;
  select id into v_location_id from public.locations where code=trim(p_target_zone) and warehouse_id=v_warehouse_id limit 1;
  if v_location_id is null then raise exception 'LOCATION_NOT_FOUND: %', p_target_zone; end if;
  select id into v_pallet_id from public.pallets where pallet_number=trim(p_target_pallet) and warehouse_id=v_warehouse_id limit 1;
  if v_pallet_id is null then raise exception 'PALLET_NOT_FOUND: %', p_target_pallet; end if;

  insert into public.box_movements (
    box_id,barcode,from_warehouse_id,to_warehouse_id,from_location_id,to_location_id,
    from_pallet_id,to_pallet_id,from_warehouse_text,to_warehouse_text,from_zone_text,to_zone_text,
    from_pallet_text,to_pallet_text,reason,operator
  )
  select b.id,b."Штрихкод",b.warehouse_id,v_warehouse_id,b.location_id,v_location_id,b.pallet_id,v_pallet_id,
         b."Склад",p_target_warehouse,b."Зона/ряд",p_target_zone,b."Поддон",p_target_pallet,'pallet_merge',p_operator
  from public.boxes b
  where exists (select 1 from jsonb_array_elements(p_source_pallets) s
                where b."Склад"=s->>'warehouse' and b."Зона/ряд"=s->>'zone' and b."Поддон"=s->>'pallet')
    and not (b."Склад"=p_target_warehouse and b."Зона/ряд"=p_target_zone and b."Поддон"=p_target_pallet);

  update public.boxes b
  set "Склад"=p_target_warehouse,"Зона/ряд"=p_target_zone,"Поддон"=p_target_pallet,
      warehouse_id=v_warehouse_id,location_id=v_location_id,pallet_id=v_pallet_id,"Изменил"=p_operator
  where exists (select 1 from jsonb_array_elements(p_source_pallets) s
                where b."Склад"=s->>'warehouse' and b."Зона/ряд"=s->>'zone' and b."Поддон"=s->>'pallet')
    and not (b."Склад"=p_target_warehouse and b."Зона/ряд"=p_target_zone and b."Поддон"=p_target_pallet);
  get diagnostics v_moved_count=row_count;
  return coalesce(v_moved_count,0);
end;
$$;

-- 9) Atomic inventory application. Every UPDATE/INSERT/history row is
-- inside this function's single transaction. Any exception rolls back all changes.
drop function if exists public.sp_apply_inventory(text,text,text,text,timestamptz,text,bigint[],bigint[],text[],bigint,bigint,bigint,integer,integer,jsonb);
create or replace function public.sp_apply_inventory(
  p_warehouse text,
  p_zone text,
  p_pallet text,
  p_started_at timestamptz,
  p_finished_at timestamptz,
  p_operator text,
  p_missing_ids bigint[],
  p_outside_ids bigint[],
  p_unknown_barcodes text[],
  p_target_warehouse_id bigint,
  p_target_location_id bigint,
  p_target_pallet_id bigint,
  p_scanned_count integer,
  p_expected_count integer,
  p_details jsonb
)
returns jsonb
language plpgsql security definer set search_path=public
as $$
declare
  v_operator text := coalesce(auth.jwt()->>'email', p_operator);
  v_removed integer := 0;
  v_moved integer := 0;
  v_created integer := 0;
  v_history_id bigint;
  v_inventory_no bigint;
  v_expected integer := coalesce(p_expected_count,0);
  v_missing integer := coalesce(array_length(p_missing_ids,1),0);
  v_outside integer := coalesce(array_length(p_outside_ids,1),0);
  v_unknown integer := coalesce(array_length(p_unknown_barcodes,1),0);
begin
  if not public.skladaplan_is_admin() then
    raise exception 'FORBIDDEN: admin role required';
  end if;

  if p_target_warehouse_id is null or p_target_location_id is null or p_target_pallet_id is null then
    raise exception 'INVALID_INVENTORY_TARGET';
  end if;

  update public.boxes
  set "Поддон"=null, pallet_id=null, "Изменил"=v_operator
  where id=any(coalesce(p_missing_ids,'{}'::bigint[]))
    and "Склад"=p_warehouse
    and "Зона/ряд"=p_zone
    and ("Поддон"=p_pallet or pallet_id=p_target_pallet_id);
  get diagnostics v_removed=row_count;
  if v_removed <> v_missing then
    raise exception 'INVENTORY_CONFLICT: expected % missing updates, changed %', v_missing, v_removed;
  end if;

  update public.boxes
  set "Склад"=p_warehouse, "Зона/ряд"=p_zone, "Поддон"=p_pallet,
      warehouse_id=p_target_warehouse_id, location_id=p_target_location_id,
      pallet_id=p_target_pallet_id, "Изменил"=v_operator
  where id=any(coalesce(p_outside_ids,'{}'::bigint[]));
  get diagnostics v_moved=row_count;
  if v_moved <> v_outside then
    raise exception 'INVENTORY_CONFLICT: expected % outside updates, changed %', v_outside, v_moved;
  end if;

  if v_unknown > 0 then
    insert into public.boxes (
      "Штрихкод","Артикул","Кол-во в коробке","Зона/ряд","Поддон","Статус",
      "ДатаРазмещения","Склад","Изменил",warehouse_id,location_id,pallet_id
    )
    select b,null,null,p_zone,p_pallet,'На складе',current_date,p_warehouse,v_operator,
           p_target_warehouse_id,p_target_location_id,p_target_pallet_id
    from unnest(p_unknown_barcodes) as u(b);
    get diagnostics v_created=row_count;
  end if;

  insert into public.inventory_history (
    warehouse,zone,pallet,started_at,finished_at,applied_at,user_email,
    expected_count,scanned_count,missing_count,outside_count,unknown_count,
    actual_count,moved_count,removed_count,created_count,details
  ) values (
    p_warehouse,p_zone,p_pallet,p_started_at,p_finished_at,now(),v_operator,
    v_expected,coalesce(p_scanned_count,0),v_missing,v_outside,v_unknown,
    coalesce(p_scanned_count,0)+v_outside+v_unknown,v_moved,v_removed,v_created,
    coalesce(p_details,'{}'::jsonb)
  )
  returning id,inventory_no into v_history_id,v_inventory_no;

  return jsonb_build_object(
    'history_id',v_history_id,
    'inventory_no',v_inventory_no,
    'moved_count',v_moved,
    'removed_count',v_removed,
    'created_count',v_created
  );
end;
$$;

