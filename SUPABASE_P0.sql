create or replace function public.sp_collect_boxes(
  p_box_ids bigint[], p_operator text, p_direction text default null
)
returns setof public.boxes
language plpgsql security definer set search_path = public
as $$
begin
  if not public.skladaplan_is_admin() then
    raise exception 'FORBIDDEN: admin role required';
  end if;
  if coalesce(array_length(p_box_ids,1),0) = 0 then
    raise exception 'EMPTY_BOX_LIST';
  end if;
  return query
  update public.boxes
  set "Статус"='Скомплектовано', "Изменил"=p_operator,
      collected_at=now(), collected_by=p_operator,
      "Направление"=coalesce(nullif(p_direction,''),"Направление")
  where id=any(p_box_ids) and "Статус"='КПодбору'
  returning *;
end;
$$;

